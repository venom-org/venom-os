//! Login/session integration: run `venom-os up` at login and give
//! every login session venom-os's `$XDG_CONFIG_DIRS`, so a `venomx` typed in
//! an ordinary terminal reads the curated defaults (`daemon.interactive_start
//! = false`) even while the supervised daemon is down, and fails
//! `unavailable.not_running` instead of starting an on-demand daemon.
//!
//! `venom-os login install` writes, only under the user's XDG config home:
//!
//! * `systemd/user/venom-os.service`, a systemd user unit running
//!   `venom-os up` (absolute paths, resolved at install time);
//! * `systemd/user/default.target.wants/venom-os.service`, the symlink
//!   `systemctl --user enable` would make, so the unit starts at the next
//!   login (skipped with `--enable=false`);
//! * `environment.d/50-venom-os.conf`, which puts venom-os's directory first
//!   in `$XDG_CONFIG_DIRS` for the user manager, its services and the login
//!   sessions that import it;
//!
//! and installs the defaults file, so it exists before the first `up`. It
//! never runs `systemctl`; it prints the command to start the unit now.
//! `venom-os env` prints the same `$XDG_CONFIG_DIRS` as a POSIX shell snippet
//! for shells and sessions that do not read environment.d
//! (`eval "$(venom-os env)"` in a shell rc). `venom-os login uninstall`
//! removes exactly the files `install` wrote (each carries `marker`).
const std = @import("std");
const xdg = @import("xdg");
const up = @import("up.zig");

pub const unit_name = "venom-os.service";
/// The first line of every file `install` writes; `uninstall` and a second
/// `install` only touch files that carry it.
pub const marker = "# Generated by `venom-os login install`; `venom-os login uninstall` removes it.";
pub const start_hint = "systemctl --user daemon-reload && systemctl --user start " ++ unit_name;
pub const stop_hint = "systemctl --user stop " ++ unit_name;

pub const Paths = struct {
    /// venom-os's `$XDG_CONFIG_DIRS` entry (holds `venomx/defaults.zon`).
    config_dir: []const u8,
    unit: []const u8,
    wants: []const u8,
    env: []const u8,

    pub fn resolve(a: std.mem.Allocator, environ: std.process.Environ) !Paths {
        const config = try xdg.base(a, .config, .{ .environ = environ, .uid = @intCast(std.c.getuid()) });
        return .{
            .config_dir = try up.configDir(a, environ),
            .unit = try std.fmt.allocPrint(a, "{s}/systemd/user/{s}", .{ config, unit_name }),
            .wants = try std.fmt.allocPrint(a, "{s}/systemd/user/default.target.wants/{s}", .{ config, unit_name }),
            .env = try std.fmt.allocPrint(a, "{s}/environment.d/50-venom-os.conf", .{config}),
        };
    }
};

/// A directory that can go into environment.d and a shell snippet without
/// quoting: absolute, and no whitespace, quotes, `$`, `\`, backquote or `:`.
pub fn plainPath(p: []const u8) bool {
    if (!std.fs.path.isAbsolute(p)) return false;
    for (p) |c| if (c < 0x21 or c == 0x7f or std.mem.indexOfScalar(u8, "\"'$\\`:;&|<>()*?[]{}#~!%", c) != null) return false;
    return true;
}

/// One ExecStart argument, double-quoted for systemd (`%` and `$` doubled).
/// Null for arguments systemd cannot carry (control characters).
fn execArg(a: std.mem.Allocator, out: *std.ArrayList(u8), arg: []const u8) !bool {
    try out.append(a, '"');
    for (arg) |c| {
        if (c < 0x20 or c == 0x7f) return false;
        switch (c) {
            '"', '\\' => try out.appendSlice(a, &.{ '\\', c }),
            '%' => try out.appendSlice(a, "%%"),
            '$' => try out.appendSlice(a, "$$"),
            else => try out.append(a, c),
        }
    }
    try out.append(a, '"');
    return true;
}

/// The systemd user unit. Null when a path cannot be written into ExecStart.
pub fn unitText(a: std.mem.Allocator, exe: []const u8, venomx: []const u8) !?[]const u8 {
    var exec: std.ArrayList(u8) = .empty;
    if (!try execArg(a, &exec, exe)) return null;
    try exec.appendSlice(a, " up ");
    if (!try execArg(a, &exec, try std.fmt.allocPrint(a, "--venomx={s}", .{venomx}))) return null;
    return try std.mem.concat(a, u8, &.{ unit_head, exec.items, unit_tail });
}

const unit_head = marker ++
    \\
    \\[Unit]
    \\Description=venom-os: the Venom bundle (supervises a persistent venomx serve)
    \\
    \\[Service]
    \\Type=exec
    \\ExecStart=
;
const unit_tail =
    \\
    \\# venom-os up stops venomx itself on SIGTERM; only then is the rest killed.
    \\KillMode=mixed
    \\TimeoutStopSec=15
    \\Restart=on-failure
    \\RestartSec=2
    \\# 2: bad usage; 5: conflict (venom-os, or an unsupervised venomx, already
    \\# holds its socket). Restarting would not help.
    \\RestartPreventExitStatus=2 5
    \\
    \\[Install]
    \\WantedBy=default.target
    \\
;

/// The environment.d snippet: venom-os first, then the inherited list.
pub fn envText(a: std.mem.Allocator, config_dir: []const u8) ![]const u8 {
    std.debug.assert(plainPath(config_dir));
    return std.fmt.allocPrint(a,
        \\{s}
        \\# venomx clients in every login session read venom-os's curated defaults,
        \\# also while `venom-os up` is down, and never start a second daemon.
        \\XDG_CONFIG_DIRS={s}:${{XDG_CONFIG_DIRS:-/etc/xdg}}
        \\
    , .{ marker, config_dir });
}

/// The POSIX shell snippet `venom-os env` prints: idempotent, so sourcing
/// it twice (nested shells) does not repeat the entry.
pub fn shText(a: std.mem.Allocator, config_dir: []const u8) ![]const u8 {
    std.debug.assert(plainPath(config_dir));
    return std.fmt.allocPrint(a,
        \\case ":${{XDG_CONFIG_DIRS:-}}:" in *":{0s}:"*) ;; *) XDG_CONFIG_DIRS="{0s}:${{XDG_CONFIG_DIRS:-/etc/xdg}}"; export XDG_CONFIG_DIRS ;; esac
        \\
    , .{config_dir});
}

/// `venomx` as the unit should run it: absolute paths stay, a bare name is
/// looked up in `$PATH` now (the user manager's PATH is usually shorter than
/// a shell's), and is kept bare when not found.
pub fn resolveVenomx(a: std.mem.Allocator, io: std.Io, environ: std.process.Environ, venomx: []const u8) ![]const u8 {
    if (std.mem.indexOfScalar(u8, venomx, '/') != null) return venomx;
    var it = std.mem.splitScalar(u8, environ.getPosix("PATH") orelse "", ':');
    while (it.next()) |dir| {
        if (!std.fs.path.isAbsolute(dir)) continue;
        const candidate = try std.fs.path.join(a, &.{ dir, venomx });
        std.Io.Dir.cwd().access(io, candidate, .{ .execute = true }) catch continue;
        return candidate;
    }
    return venomx;
}

pub const Owner = enum { absent, ours, foreign };

/// Whether `path` is missing, a file `install` wrote, or someone else's.
pub fn owner(a: std.mem.Allocator, io: std.Io, path: []const u8) Owner {
    const text = std.Io.Dir.cwd().readFileAlloc(io, path, a, .limited(1 << 16)) catch |err| return switch (err) {
        error.FileNotFound => .absent,
        else => .foreign,
    };
    return if (std.mem.startsWith(u8, text, marker)) .ours else .foreign;
}

/// Whether `wants` is a symlink to `unit`.
pub fn linksTo(io: std.Io, wants: []const u8, unit: []const u8) bool {
    var buf: [std.fs.max_path_bytes]u8 = undefined;
    const n = std.Io.Dir.cwd().readLink(io, wants, &buf) catch return false;
    return std.mem.eql(u8, buf[0..n], unit);
}

pub fn writeFile(io: std.Io, path: []const u8, bytes: []const u8) !void {
    var file = try std.Io.Dir.cwd().createFileAtomic(io, path, .{ .make_path = true, .replace = true, .permissions = .fromMode(0o644) });
    defer file.deinit(io);
    var buffer: [4096]u8 = undefined;
    var writer = file.file.writer(io, &buffer);
    try writer.interface.writeAll(bytes);
    try writer.interface.flush();
    try file.file.sync(io);
    try file.replace(io);
}

/// Points `wants` at `unit`, replacing an older link to it.
pub fn link(io: std.Io, wants: []const u8, unit: []const u8) !void {
    const cwd = std.Io.Dir.cwd();
    try cwd.createDirPath(io, std.fs.path.dirname(wants).?);
    cwd.deleteFile(io, wants) catch |err| if (err != error.FileNotFound) return err;
    try cwd.symLink(io, unit, wants, .{});
}

const t = std.testing;

test "unitText: quoted absolute ExecStart, restart policy, WantedBy default.target" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const unit = (try unitText(a, "/opt/my bin/venom-os", "/usr/bin/venomx")).?;
    try t.expect(std.mem.startsWith(u8, unit, marker ++ "\n[Unit]\n"));
    try t.expect(std.mem.indexOf(u8, unit, "\nExecStart=\"/opt/my bin/venom-os\" up \"--venomx=/usr/bin/venomx\"\n") != null);
    try t.expect(std.mem.indexOf(u8, unit, "\nWantedBy=default.target\n") != null);
    try t.expect(std.mem.indexOf(u8, unit, "\nRestartPreventExitStatus=2 5\n") != null);
    const odd = (try unitText(a, "/x/50%$\"\\", "venomx")).?;
    try t.expect(std.mem.indexOf(u8, odd, "ExecStart=\"/x/50%%$$\\\"\\\\\" up") != null);
    try t.expect(try unitText(a, "/x/a\nb", "venomx") == null);
}

test "envText and shText put venom-os first and keep the inherited list" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const env = try envText(a, "/h/.local/share/venom/venom-os/xdg");
    try t.expect(std.mem.startsWith(u8, env, marker ++ "\n"));
    try t.expect(std.mem.endsWith(u8, env, "\nXDG_CONFIG_DIRS=/h/.local/share/venom/venom-os/xdg:${XDG_CONFIG_DIRS:-/etc/xdg}\n"));
    const sh = try shText(a, "/h/x");
    try t.expectEqualStrings("case \":${XDG_CONFIG_DIRS:-}:\" in *\":/h/x:\"*) ;; *) XDG_CONFIG_DIRS=\"/h/x:${XDG_CONFIG_DIRS:-/etc/xdg}\"; export XDG_CONFIG_DIRS ;; esac\n", sh);
}

test "plainPath rejects relative paths and shell or list metacharacters" {
    try t.expect(plainPath("/home/u/.local/share/venom/venom-os/xdg"));
    for ([_][]const u8{ "rel/x", "/a b", "/a:b", "/a$b", "/a\"b", "/a'b", "/a\\b", "/a`b", "/a\nb" }) |p| try t.expect(!plainPath(p));
}

test "Paths.resolve follows XDG_CONFIG_HOME and XDG_DATA_HOME" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const block = [_:null]?[*:0]const u8{ "XDG_CONFIG_HOME=/h/cfg", "XDG_DATA_HOME=/h/data", "HOME=/h" };
    const p = try Paths.resolve(arena.allocator(), .{ .block = .{ .slice = &block } });
    try t.expectEqualStrings("/h/data/venom/venom-os/xdg", p.config_dir);
    try t.expectEqualStrings("/h/cfg/systemd/user/venom-os.service", p.unit);
    try t.expectEqualStrings("/h/cfg/systemd/user/default.target.wants/venom-os.service", p.wants);
    try t.expectEqualStrings("/h/cfg/environment.d/50-venom-os.conf", p.env);
}

test "owner, writeFile, link and linksTo in a temp dir" {
    var tmp = t.tmpDir(.{});
    defer tmp.cleanup();
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const base = try tmp.dir.realPathFileAlloc(t.io, ".", a);
    const unit = try std.fmt.allocPrint(a, "{s}/u/venom-os.service", .{base});
    const wants = try std.fmt.allocPrint(a, "{s}/u/default.target.wants/venom-os.service", .{base});
    try t.expectEqual(Owner.absent, owner(a, t.io, unit));
    try writeFile(t.io, unit, "[Unit]\n");
    try t.expectEqual(Owner.foreign, owner(a, t.io, unit));
    try writeFile(t.io, unit, marker ++ "\n[Unit]\n");
    try t.expectEqual(Owner.ours, owner(a, t.io, unit));
    try t.expect(!linksTo(t.io, wants, unit));
    try link(t.io, wants, unit);
    try link(t.io, wants, unit);
    try t.expect(linksTo(t.io, wants, unit));
}
